$count = 0;

foreach ($updates as $type => $texts) {
    $howToUse = $texts[0];
    $rows = PromotionNotification::where('type', $type)
        ->whereNull('how_to_use')
        ->get();

    foreach ($rows as $row) {
        $row->how_to_use = $howToUse;
        $row->save();
        echo "✅ Updated [{$type}] ID={$row->id}: {$row->title}\n";
        $count++;
    }
}

if ($count === 0) {
    echo "ℹ️  ไม่มีรายการที่ต้องอัปเดต (how_to_use ถูกกรอกไว้ทั้งหมดแล้ว)\n";
} else {
    echo "\n✅ อัปเดตทั้งหมด {$count} รายการ\n";
}
