<?php

namespace Database\Seeders;

use App\Models\Country;
use App\Models\InternationalTourCountryCover;
use App\Models\InternationalTourSetting;
use Illuminate\Database\Seeder;

/**
 * Seeds per-country long descriptions (thin-content SEO fix) into the
 * international_tour_country_covers.intro_html column, attached to the SAME
 * active setting the public /tours/country/{slug} page reads.
 *
 * Idempotent: only intro_html is written (image_url / hero_text / pinned tours
 * on an existing cover row are preserved). Re-running just refreshes the text.
 *
 * Run:  php artisan db:seed --class=CountryIntroSeeder --force
 */
class CountryIntroSeeder extends Seeder
{
    public function run(): void
    {
        $setting = InternationalTourSetting::active()->orderBy('sort_order')->first()
            ?? InternationalTourSetting::orderBy('sort_order')->first();

        if (! $setting) {
            $this->command->warn('No international_tour_settings row found — cannot attach country covers. Skipped.');
            return;
        }

        $this->command->info("Attaching country intros to setting #{$setting->id}.");

        foreach ($this->intros() as $slug => $paras) {
            $countryId = Country::where('slug', $slug)->value('id');
            if (! $countryId) {
                $this->command->warn("  country slug '{$slug}' not found — skipped.");
                continue;
            }

            $html = '<p>' . $paras[0] . '</p><p>' . $paras[1] . '</p>';

            $cover = InternationalTourCountryCover::firstOrNew([
                'setting_id' => $setting->id,
                'country_id' => $countryId,
            ]);
            $existed = $cover->exists;
            $cover->intro_html = $html;
            $cover->save();

            $this->command->line('  ' . ($existed ? 'updated' : 'created') . " intro: {$slug}");
        }

        $this->command->info('CountryIntroSeeder done.');
    }

